// Read the Maps API key from local.properties (never hard-coded, never committed).
// Falls back to a placeholder so the project always builds; the app itself detects
// the placeholder at runtime and shows a friendly "Maps API key missing" message
// instead of crashing.
val localProperties = Properties().apply {
    val localPropsFile = rootProject.file("local.properties")
    if (localPropsFile.exists()) {
        load(FileInputStream(localPropsFile))
    }
}
val mapsApiKey: String = (localProperties.getProperty("MAPS_API_KEY")
    ?: System.getenv("MAPS_API_KEY")
    ?: "YOUR_GOOGLE_MAPS_API_KEY")

